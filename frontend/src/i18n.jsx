function makeTn(lang, t) {
  const rules = new Intl.PluralRules(lang === "fr" ? "fr-CA" : "en-CA");
  return (key, n) => t(`${key}_${rules.select(Number(n) || 0)}`) ?? t(`${key}_other`);
}

const defaultT = (k) => STRINGS.en[k] || k;
const LangContext = createContext({ lang: "en", setLang: () => {}, t: defaultT, tn: makeTn("en", defaultT) });

function storedLang() {
  try {
    return localStorage.getItem("lang");
  } catch {
    return null;
  }
}

// Language persists across the separate HTML entry points through the
// same "lang" localStorage key the static About/legal pages read.
export function LangProvider({ children }) {
  const [lang, setLang] = useState(
    () => storedLang() || (navigator.language?.startsWith("fr") ? "fr" : "en")
  );
  function changeLang(next) {
    try {
      localStorage.setItem("lang", next);
    } catch {
      /* storage blocked: choice still applies for this page */
    }
    setLang(next);
  }
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const t = (key) => STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  const tn = makeTn(lang, t);
  return (
    <LangContext.Provider value={{ lang, setLang: changeLang, t, tn }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}
